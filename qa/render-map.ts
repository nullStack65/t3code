// Renders docs/FEATURES.md and qa/report/index.html from features.ts and status.json.
// @effect-diagnostics nodeBuiltinImport:off - a plain Node script, outside the server's Effect runtime.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import { FEATURES } from "./features.ts";

const QA = import.meta.dirname;
const ROOT = NodePath.resolve(QA, "..");

interface Entry {
  readonly status: "verified" | "broken" | "unverified";
  readonly sha: string;
  readonly date: string;
  readonly reason?: string;
  readonly visual?: "pending";
  readonly projects: Record<string, string>;
  readonly errors?: Record<string, string>;
}
interface Status {
  readonly sha: string;
  readonly date: string;
  readonly target: string;
  readonly dirty?: boolean;
  readonly features: Record<string, Entry>;
}

const loadStatus = (partial: boolean): Status | undefined => {
  const file = partial
    ? NodePath.join(QA, "test-results", "status-partial.json")
    : NodePath.join(QA, "status.json");
  return NodeFS.existsSync(file)
    ? (JSON.parse(NodeFS.readFileSync(file, "utf8")) as Status)
    : undefined;
};

const label = (entry: Entry | undefined, reason: string | undefined) =>
  entry === undefined
    ? `unverified: ${reason ?? "not yet swept"}`
    : entry.status === "verified"
      ? `verified: ${entry.sha} ${entry.date}${entry.visual === "pending" ? " (clicks only; visual baselines pending)" : ""}`
      : entry.status === "broken"
        ? `broken: ${entry.sha} ${entry.date}`
        : `unverified: ${entry.reason ?? reason ?? "no result"}`;

const escape = (text: string) =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** A partial run renders only qa/report/index.html, marked as partial; docs/FEATURES.md stays as it was. */
export const renderReport = (partialProjects?: ReadonlyArray<string>) => {
  const partial = partialProjects !== undefined;
  const status = loadStatus(partial);
  const areas = [...new Set(FEATURES.map((feature) => feature.area))];

  const md = [
    "# T3 Code feature map",
    "",
    "Generated by `node qa/render-map.ts` from `qa/features.ts` and `qa/status.json`. Edit the map in `qa/features.ts`; prove it with `node qa/verify.ts`. Do not edit this file by hand.",
    "",
    "Each entry is a user-facing feature: how a user reaches it, how an agent drives it with Playwright, the observable state that means it works, and `verified: <sha> <date>` (every viewport and color scheme passed on that commit), `broken: <sha> <date>` (a run failed), or `unverified: <reason>`. The name-level site map of every label and shortcut is [feature-map.md](../.agents/skills/test-t3-app/references/feature-map.md); the ids here follow it.",
    "",
    status
      ? `Last sweep: ${status.sha}${status.dirty ? " (dirty tree)" : ""} on ${status.date}, target: ${status.target}. Projects: desktop (1440×900) and phone (390×844), each in light and dark.`
      : "Not swept yet.",
    "",
  ];
  const html: string[] = [];
  const total = { verified: 0, broken: 0, unverified: 0 };
  for (const feature of FEATURES) total[status?.features[feature.id]?.status ?? "unverified"]++;
  md.push(
    `**${total.verified} verified, ${total.broken} broken, ${total.unverified} unverified** of ${FEATURES.length} features.`,
    "",
  );

  for (const area of areas) {
    md.push(`## ${area}`, "");
    html.push(`<h2>${escape(area)}</h2><div class="grid">`);
    for (const feature of FEATURES.filter((candidate) => candidate.area === area)) {
      const entry = status?.features[feature.id];
      md.push(
        `### ${feature.id} — ${feature.title}`,
        "",
        `- **Path:** ${feature.path}`,
        `- **Drive:** ${feature.drive.map((step, index) => `${index + 1}. ${step}`).join(" ")}`,
        `- **Success:** ${feature.success}`,
        `- **Code:** ${feature.code.map((code) => `\`${code}\``).join(", ")}`,
        `- **Status:** ${label(entry, feature.unverified)}`,
        ...(entry?.status === "broken"
          ? Object.entries(entry.errors ?? {}).map(([project, error]) => `  - ${project}: ${error}`)
          : []),
        "",
      );
      const shotsDir = NodePath.join(QA, "report", "shots", feature.id);
      const shots = NodeFS.existsSync(shotsDir)
        ? NodeFS.readdirSync(shotsDir)
            .filter((file) => file.endsWith(".png"))
            .toSorted()
        : [];
      const state = entry?.status ?? "unverified";
      html.push(
        `<section class="card ${state}" id="${escape(feature.id)}"><header><h3>${escape(feature.id)}</h3><span class="badge ${state}">${escape(label(entry, feature.unverified))}</span></header>`,
        `<p class="title">${escape(feature.title)}</p><p class="path">${escape(feature.path)}</p>`,
        `<details><summary>Drive steps and success state</summary><ol>${feature.drive.map((step) => `<li>${escape(step)}</li>`).join("")}</ol><p><b>Success:</b> ${escape(feature.success)}</p></details>`,
        ...(entry?.status === "broken"
          ? [
              `<pre class="errors">${escape(
                Object.entries(entry.errors ?? {})
                  .map(([project, error]) => `${project}: ${error}`)
                  .join("\n"),
              )}</pre>`,
            ]
          : []),
        `<div class="shots">${shots.map((file) => `<a href="shots/${escape(feature.id)}/${escape(file)}"><img loading="lazy" src="shots/${escape(feature.id)}/${escape(file)}" alt="${escape(`${feature.id} ${file}`)}"><span>${escape(file.replace(/\.png$/, ""))}</span></a>`).join("")}</div></section>`,
      );
    }
    html.push("</div>");
  }

  if (!partial) {
    NodeFS.mkdirSync(NodePath.join(ROOT, "docs"), { recursive: true });
    NodeFS.writeFileSync(NodePath.join(ROOT, "docs", "FEATURES.md"), `${md.join("\n")}\n`);
  }
  NodeFS.mkdirSync(NodePath.join(QA, "report"), { recursive: true });
  NodeFS.writeFileSync(
    NodePath.join(QA, "report", "index.html"),
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>T3 Code feature status</title><style>
:root{color-scheme:light dark;--bg:#fff;--fg:#14161a;--mut:#5d6470;--line:#dfe3ea;--ok:#12794a;--bad:#b42318;--warn:#8a6100}
@media(prefers-color-scheme:dark){:root{--bg:#101215;--fg:#e8eaee;--mut:#98a0ac;--line:#2a2f37;--ok:#4cc38a;--bad:#ff7b72;--warn:#e3b341}}
body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;padding:24px;max-width:1400px;margin-inline:auto}
h1{margin:0 0 4px}h2{margin:32px 0 12px;border-bottom:1px solid var(--line);padding-bottom:6px}.sum{display:flex;gap:16px;flex-wrap:wrap;margin:12px 0 4px}.sum b{font-size:22px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(420px,1fr));gap:12px}.card{border:1px solid var(--line);border-left:4px solid var(--warn);border-radius:8px;padding:12px}
.card.verified{border-left-color:var(--ok)}.card.broken{border-left-color:var(--bad)}header{display:flex;justify-content:space-between;gap:8px;align-items:baseline}h3{margin:0;font-size:14px;font-family:ui-monospace,monospace}
.badge{font-size:12px;color:var(--warn)}.badge.verified{color:var(--ok)}.badge.broken{color:var(--bad)}.title{font-weight:600;margin:6px 0 0}.path{color:var(--mut);margin:2px 0 6px}
.shots{display:grid;grid-template-columns:repeat(auto-fill,minmax(120px,1fr));gap:8px;margin-top:8px}.shots a{color:var(--mut);font-size:11px;text-decoration:none}.shots img{width:100%;border:1px solid var(--line);border-radius:4px;display:block}
pre.errors{white-space:pre-wrap;color:var(--bad);font-size:12px}
</style></head><body><h1>T3 Code feature status</h1>${partial ? `<p><b>Partial run (${escape((partialProjects ?? []).join(", "))}): not the full sweep. A feature marked verified here passed in only these projects.</b></p>` : ""}<p>${status ? `Sweep ${escape(status.sha)}${status.dirty ? " (dirty tree)" : ""} on ${escape(status.date)}. Target: ${escape(status.target)}. Desktop 1440 and phone 390, light and dark.` : "Not swept yet."}</p>
<div class="sum"><span><b style="color:var(--ok)">${total.verified}</b> verified</span><span><b style="color:var(--bad)">${total.broken}</b> broken</span><span><b style="color:var(--warn)">${total.unverified}</b> unverified</span><span>of ${FEATURES.length}</span></div>
${html.join("\n")}</body></html>`,
  );
};

if (import.meta.main) renderReport();
