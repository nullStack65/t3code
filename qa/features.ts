// The feature map: one entry per user-facing feature. docs/FEATURES.md is rendered from this file
// and qa/status.json, which `node qa/verify.ts` writes; never hand-edit status here.
// A feature no spec can drive carries `unverified: <reason>`. A PR that changes a file in an entry's
// `code` must change that entry, its spec or status.json (`node qa/check-map.ts --changed <base>`).

export interface Feature {
  /** Stable id, `area.feature`. Matches the names in .agents/skills/test-t3-app/references/feature-map.md where one exists. */
  readonly id: string;
  readonly area: string;
  readonly title: string;
  /** How a user gets to it, in their words. Every entry point listed here needs a spec step. */
  readonly path: string;
  /** What the spec does, as Playwright-level steps. */
  readonly drive: ReadonlyArray<string>;
  /** The observable state that means it works. */
  readonly success: string;
  /** Source paths (files, or directories ending in `/`) that implement it. */
  readonly code: ReadonlyArray<string>;
  /** Set when no spec can prove it on this harness. The report shows it as unverified with this reason. */
  readonly unverified?: string;
}

